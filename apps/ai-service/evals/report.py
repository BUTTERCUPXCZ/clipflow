"""Markdown for the Phase 4 eval: measured metrics, a hand-scoring sheet, and a speed-only recommendation."""

from datetime import date
from pathlib import Path


def seconds_per_frame(run: dict) -> float | None:
    m = run.get("metrics")
    return m["inferenceMs"] / 1000 / m["framesAnalysed"] if m and m["framesAnalysed"] else None


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def metrics_table(videos: list[dict]) -> list[str]:
    rows = [
        "| Video | Frames/request | Status | s/frame | Total | Load | Peak VRAM | Valid batches |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for v in videos:
        for run in v["runs"]:
            m = run.get("metrics") or {}
            spf = seconds_per_frame(run)
            vram = m.get("peakVramMiB")
            rows.append(
                f"| {_cell(v['video']['filename'])} | {run['settings']['batchSize']} | {run['status']} "
                f"| {f'{spf:.1f}' if spf is not None else '—'} | {m.get('totalMs', 0) / 1000:.0f} s "
                f"| {m.get('loadMs', 0) / 1000:.1f} s | {f'{vram} MiB' if vram is not None else 'unknown'} "
                f"| {m.get('validBatches', '—')} / {m.get('totalBatches', '—')} |"
            )
    return rows


def whisper_table(videos: list[dict]) -> list[str]:
    rows = ["| Video | Whisper | Time | × real time | Segments |", "|---|---|---|---|---|"]
    for v in videos:
        for w in v["whisper"]:
            if "skipped" in w:
                rows.append(f"| {_cell(v['video']['filename'])} | {w['model']} | {w['skipped']} | | |")
            else:
                rows.append(
                    f"| {_cell(v['video']['filename'])} | {w['model']} | {w['seconds']:.0f} s "
                    f"| {w['realtimeFactor']:.2f} | {w['segments']} |"
                )
    return rows


def scoring_sheet(v: dict, api_url: str) -> list[str]:
    """One row per timestamp: what each setting saw, with blank score columns (0 wrong, 1 partly, 2 right)."""
    runs = [r for r in v["runs"] if r["status"] == "COMPLETED" and r.get("output")]
    if not runs:
        return ["No completed runs to score."]
    by_time: dict[float, dict[int, dict]] = {}
    for i, run in enumerate(runs):
        for scene in run["output"]["scenes"]:
            by_time.setdefault(scene["timestampSeconds"], {})[i] = scene
    frames = {f["timestampSeconds"]: f["index"] for f in runs[0]["output"]["frames"]}
    labels = [f"{r['settings']['batchSize']}/request" for r in runs]
    header = "| Time | Frame | " + " | ".join(f"{label} | Score" for label in labels) + " | Crop right? |"
    rows = [header, "|" + "---|" * (2 + 2 * len(runs) + 1)]
    for t in sorted(by_time):
        frame = f"[{frames[t]}]({api_url}/jobs/{v['job']['id']}/frames/{frames[t]})" if t in frames else "—"
        cells = []
        for i in range(len(runs)):
            s = by_time[t].get(i)
            cells.append(_cell(f"{s['description']} ({s['cameraFraming']}, crop {'ok' if s['verticalCropSuitable'] else 'no'})") if s else "*no valid answer*")
            cells.append(" ")
        rows.append(f"| {t:.1f} s | {frame} | " + " | ".join(cells) + " |   |")
    return rows


def recommendation(videos: list[dict]) -> str:
    """Speed and validity only: quality comes from the scoring sheet."""
    totals: dict[int, list[float]] = {}
    valid: dict[int, list[float]] = {}
    for v in videos:
        for run in v["runs"]:
            spf, m = seconds_per_frame(run), run.get("metrics")
            if spf is None or not m:
                continue
            totals.setdefault(run["settings"]["batchSize"], []).append(spf)
            valid.setdefault(run["settings"]["batchSize"], []).append(m["validBatches"] / max(m["totalBatches"], 1))
    if not totals:
        return "No run completed, so there is no recommendation."
    stats = {b: (sum(t) / len(t), sum(valid[b]) / len(valid[b])) for b, t in totals.items()}
    best = min(stats, key=lambda b: (-round(stats[b][1], 2), stats[b][0]))
    lines = [f"- {b} frames/request: {spf:.1f} s/frame on average, {ratio:.0%} of batches valid" for b, (spf, ratio) in sorted(stats.items())]
    return "\n".join(
        [*lines, "", f"**Speed + validity pick: {best} frames per request** (the highest validity, then the fastest). "
         "Confirm with the scoring sheet before changing `VISION_BATCH_SIZE`: a faster setting that describes frames worse is not better."]
    )


def write_report(out: Path, model: str, api_url: str, videos: list[dict]) -> None:
    lines = [
        "# Phase 4 eval: vision settings and Whisper size",
        "",
        f"Run on {date.today().isoformat()} with `{model}` (the default vision model) on this machine.",
        "Generated by `apps/ai-service/evals/run_eval.py`. The metrics are measured; fill in the scores by hand.",
        "",
        "## Vision: frames per request",
        "",
        *metrics_table(videos),
        "",
        recommendation(videos),
        "",
        "## Whisper (CPU, int8)",
        "",
        *whisper_table(videos),
        "",
    ]
    for v in videos:
        for w in v["whisper"]:
            if "sample" in w:
                lines += [f"- {_cell(v['video']['filename'])}, {w['model']}: “{_cell(w['sample'])}…”"]
    lines += ["", "## Scoring sheet", "", "Score each description: 0 wrong, 1 partly right, 2 right. Mark if the crop advice is right.", ""]
    for v in videos:
        lines += [f"### {v['video']['filename']}", "", *scoring_sheet(v, api_url), ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
